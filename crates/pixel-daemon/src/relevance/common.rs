//! General words that say nothing about a repository.
//!
//! A prompt about any code base is full of them (`does`, `handle`, `existing`,
//! `way`, `thing`, `quel`, `chose`, `marche`): the tokenizer keeps them because
//! it only drops function words, and a repository mentions most of them in a
//! few files by accident, which would make them look rare. Relevance lists
//! such a keyword with `common: true` and weight 0 instead of counting its
//! files. Words that name this domain (`install`, `file`, `test`, `daemon`,
//! `hook`) are not here: whether they are common is the repository's to say.
//!
//! Folded the way the tokenizer folds: lowercase ASCII, accents removed, at
//! least three letters.

